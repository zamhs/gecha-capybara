const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:'/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge'});
  const page = await browser.newPage({ viewport: {width: 1440,height:900},deviceScaleFactor:1});
  const url = `file://${path.resolve(__dirname, '..', 'index.html')}`;
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.route('https://fonts.gstatic.com/**', route => route.abort());
  await page.goto(url, {waitUntil:'domcontentloaded'});
  console.log('desktop dimensions', await page.evaluate(()=>[document.documentElement.scrollWidth,document.documentElement.scrollHeight]));
  await page.screenshot({path:path.resolve(__dirname, 'desktop.png'),fullPage:false,animations:'disabled',timeout:20000});
  assert.equal(await page.locator('h1').count(),1);
  const checkboxes = page.locator('[data-care]');
  assert.equal(await checkboxes.count(),5);
  await checkboxes.first().check();
  assert.match(await page.locator('#progress-count').textContent(),/1 de 5/);
  await page.locator('[data-hug]').first().click();
  assert.equal(await page.locator('#hug-toast').isVisible(),true);
  await page.reload();
  assert.equal(await checkboxes.first().isChecked(),true);
  await page.locator('#reset-care').click();
  assert.equal(await checkboxes.first().isChecked(),false);
  const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  await mobile.route('https://fonts.googleapis.com/**', route => route.abort());
  await mobile.route('https://fonts.gstatic.com/**', route => route.abort());
  await mobile.goto(url, {waitUntil:'domcontentloaded'});
  await mobile.screenshot({path:path.resolve(__dirname,'mobile.png'),fullPage:false,animations:'disabled',timeout:20000});
  const hasOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
  assert.equal(hasOverflow,false,'Mobile horizontal overflow detected');
  console.log('OK: desktop/mobile screenshots, checklist, persistence, reset, hug animation, no mobile overflow.');
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
